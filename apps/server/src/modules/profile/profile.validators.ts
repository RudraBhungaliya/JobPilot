import { z } from "zod";

export const createProfileSchema = z.object({
    firstName: z.string().min(1).max(100),
    middleName: z.string().max(100).optional().nullable(),
    lastName: z.string().min(1).max(100),
    email: z.string().email().optional().nullable(),
    phone: z.string().min(5).max(30),
    dateOfBirth: z.coerce.date().optional().nullable(),
    gender: z.string().optional().nullable(),
    nationality: z.string().optional().nullable(),
    address: z.string().optional().nullable(),
    city: z.string().optional().nullable(),
    state: z.string().optional().nullable(),
    country: z.string().optional().nullable(),
    zipCode: z.string().optional().nullable(),
    currentTitle: z.string().optional().nullable(),
    currentCompany: z.string().optional().nullable(),
    yearsOfExperience: z.number().optional().nullable(),
    expectedSalary: z.number().optional().nullable(),
    currentSalary: z.number().optional().nullable(),
    noticePeriod: z.number().optional().nullable(),
    noticePeriodDays: z.number().optional().nullable(),
    github: z.string().optional().nullable(),
    linkedin: z.string().optional().nullable(),
    portfolio: z.string().optional().nullable(),
    website: z.string().optional().nullable(),
    codeforces: z.string().optional().nullable(),
    leetcode: z.string().optional().nullable(),
    workMode: z.enum(["REMOTE", "HYBRID", "ONSITE"]).optional().nullable(),
    employmentType: z.enum(["FULL_TIME", "PART_TIME", "CONTRACT", "INTERNSHIP", "FREELANCE"]).optional().nullable(),
    willingToRelocate: z.boolean().optional().nullable(),
    willingToTravel: z.boolean().optional().nullable(),
    remoteOnly: z.boolean().optional().nullable(),
    sponsorshipRequired: z.boolean().optional().nullable(),
    workAuthorization: z.string().optional().nullable(),
    is18OrOlder: z.boolean().optional().nullable(),
    previousEmployee: z.boolean().optional().nullable(),
    nonCompeteAgreement: z.boolean().optional().nullable(),
    visaStatus: z.string().optional().nullable(),
    governmentEmployee: z.boolean().optional().nullable(),
    militaryService: z.boolean().optional().nullable(),
    veteran: z.boolean().optional().nullable(),
    criminalRecord: z.boolean().optional().nullable(),
    securityClearance: z.boolean().optional().nullable(),
    disability: z.boolean().optional().nullable(),
    summary: z.string().optional().nullable(),
    skills: z.array(z.object({ name: z.string().min(1), category: z.string().optional().nullable(), level: z.string().optional().nullable(), yearsOfExperience: z.number().optional().nullable() })).optional(),
    experiences: z.array(z.object({ company: z.string().min(1), title: z.string().min(1), location: z.string().optional().nullable(), description: z.string().optional().nullable(), startDate: z.coerce.date().optional().nullable(), endDate: z.coerce.date().optional().nullable(), currentlyWorking: z.boolean().optional() })).optional(),
    educations: z.array(z.object({ degree: z.string().min(1), institution: z.string().min(1), fieldOfStudy: z.string().optional().nullable(), grade: z.string().optional().nullable(), startDate: z.coerce.date().optional().nullable(), endDate: z.coerce.date().optional().nullable(), currentlyStudying: z.boolean().optional() })).optional(),
    languages: z.array(z.object({ name: z.string().min(1), proficiency: z.string().optional().nullable() })).optional(),
    certifications: z.array(z.object({ name: z.string().min(1), issuer: z.string().optional().nullable(), credentialId: z.string().optional().nullable(), credentialUrl: z.string().optional().nullable(), issuedAt: z.coerce.date().optional().nullable(), expiresAt: z.coerce.date().optional().nullable() })).optional(),
    projects: z.array(z.object({ title: z.string().min(1), description: z.string().optional().nullable(), githubUrl: z.string().optional().nullable(), liveUrl: z.string().optional().nullable(), technologies: z.string().optional().nullable() })).optional(),
});

export const updateProfileSchema = createProfileSchema.partial();

export type CreateProfileDTO = z.infer<typeof createProfileSchema>;
export type UpdateProfileDTO = z.infer<typeof updateProfileSchema>;
